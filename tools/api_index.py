#!/usr/bin/env python3
"""Generates docs/API_INDEX.md from the public headers, and checks that every indexed name is defined.

Usage:
  python3 tools/api_index.py            # write docs/API_INDEX.md
  python3 tools/api_index.py --check    # exit 1 if the index is stale or a member is not defined

The member list of cppgram::Client (include/cppgram/client.h) is extracted by brace-depth scanning, not by a C++
parser. The check then requires each member name to appear in a definition under src/, or as an inline/template
definition in a public header. Nothing here compiles or runs code.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "include" / "cppgram" / "client.h"
OUT = ROOT / "docs" / "API_INDEX.md"
SRC_DIR = ROOT / "src"
PUBLIC_HEADERS = sorted((ROOT / "include" / "cppgram").glob("*.h"))

TYPE_DECL = re.compile(r"^(class|struct|enum class|enum)\s+([A-Za-z_]\w*)\b")
# A member declaration: optional specifiers, a return type, then the name and an opening parenthesis.
MEMBER = re.compile(
    r"^(?:(?:\[\[nodiscard\]\]|static|virtual|explicit|inline|constexpr|friend)\s+)*"
    r"(?:template\s*<[^>]*>\s*)?"
    r"(?:[A-Za-z_][\w:<>,\*&\s]*?[\s\*&>])?([A-Za-z_~]\w*)\s*\("
)
SKIP_START = ("using ", "return ", "if ", "for ", "while ", "switch ", "case ", "#", "}", "static_assert", "friend ")


def strip_line_comment(line: str) -> str:
    idx = line.find("//")
    return line if idx < 0 else line[:idx]


def client_members(lines):
    """Yields (name, declaration) for each member declared at depth 1 of class Client."""
    start = next(i for i, line in enumerate(lines) if line.startswith("class Client {"))
    depth = 0
    opened = False
    pending = None  # (name, text) of a declaration that continues onto following lines
    for i in range(start, len(lines)):
        code = strip_line_comment(lines[i])
        stripped = code.strip()
        if depth == 1 and pending is None and stripped and not stripped.startswith(SKIP_START):
            match = MEMBER.match(stripped)
            if match and not TYPE_DECL.match(stripped):
                pending = [match.group(1), stripped]
        elif depth == 1 and pending is not None and stripped:
            pending[1] += " " + stripped
        for ch in code:
            if ch == "{":
                depth += 1
                opened = True
            elif ch == "}":
                depth -= 1
                if opened and depth == 0:
                    return
        if pending is not None and (";" in code or "{" in code):
            # Default arguments such as "= {}" contain a brace, so protect them before cutting the declaration.
            protected = pending[1].replace("= {}", "=\x00")
            declaration = re.split(r"[{;]", protected)[0].strip().replace("=\x00", "= {}")
            yield pending[0], declaration
            pending = None


def public_types(path: pathlib.Path):
    names = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        match = TYPE_DECL.match(raw.strip())
        if match and not raw.strip().endswith(";"):
            names.append(match.group(2))
    return names


def defined_in_source(name: str) -> bool:
    pattern = re.compile(r"\b" + re.escape(name) + r"\s*\(")
    for path in SRC_DIR.rglob("*.cpp"):
        if pattern.search(path.read_text(encoding="utf-8", errors="ignore")):
            return True
    return False


def defined_inline(name: str) -> bool:
    pattern = re.compile(r"\b" + re.escape(name) + r"\s*\([^;{]*\)\s*(const\s*)?(noexcept\s*)?\{")
    for header in PUBLIC_HEADERS:
        if pattern.search(header.read_text(encoding="utf-8", errors="ignore")):
            return True
    return False


def render(members) -> str:
    lines = [
        "# CppGram public API index",
        "",
        "Generated by `tools/api_index.py` from `include/cppgram/client.h`. Do not edit by hand. Refresh with",
        "`python3 tools/api_index.py`; verify with `python3 tools/api_index.py --check`.",
        "",
        "This is a signature index, not a behaviour description. A row means the member is declared in `client.h`",
        "and its name is defined in `src/` or inline in a public header. It does not mean the member is tested or that",
        "it matches Kurigram. For the evidence level of each Telegram method see `PARITY_MATRIX.md`. For how to use the",
        "API see `docs/API.md`.",
        "",
        f"## cppgram::Client members ({len({n for n, _ in members})} distinct names, {len(members)} declarations)",
        "",
        "| Member | Declaration |",
        "|---|---|",
    ]
    seen = set()
    for name, declaration in members:
        if declaration in seen:
            continue
        seen.add(declaration)
        escaped = declaration.replace("|", "\\|")
        lines.append(f"| `{name}` | `{escaped}` |")
    lines += ["", "## Public headers and the types they declare", "", "| Header | Types |", "|---|---|"]
    for header in PUBLIC_HEADERS:
        types = public_types(header)
        listed = ", ".join(f"`{t}`" for t in types) if types else "-"
        lines.append(f"| `include/cppgram/{header.name}` | {listed} |")
    return "\n".join(lines) + "\n"


def main(argv):
    members = list(client_members(HEADER.read_text(encoding="utf-8").splitlines()))
    if not members:
        print("FAIL no members found in class Client", file=sys.stderr)
        return 1
    text = render(members)
    if "--check" in argv:
        failures = []
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            failures.append("docs/API_INDEX.md is stale: run python3 tools/api_index.py")
        for name in sorted({n for n, _ in members}):
            if name.startswith("~") or any(d.startswith(name) and "= delete" in d or "= default" in d for n, d in members if n == name):
                continue  # destructors and deleted or defaulted members have no name-level definition to find
            if not (defined_in_source(name) or defined_inline(name)):
                failures.append(f"Client member not defined in src/ or inline in a public header: {name}")
        for failure in failures:
            print("FAIL " + failure)
        if failures:
            return 1
        print(f"OK api index: {len({n for n, _ in members})} distinct Client members, all defined")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len({n for n, _ in members})} distinct Client members")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
