#!/usr/bin/env python3
"""Writes TEST_RESULTS.md from gtest XML files.

usage: summarize_test_results.py <results_dir> <repo_root> <out_md>

<results_dir> holds one <binary>.xml per test binary (written with --gtest_output=xml:...) and, optionally, a
<binary>.rc file holding the process exit code. Test cases are attributed to source files by the suite name in
TEST, TEST_F and TEST_P macros under <repo_root>/tests. Nothing is inferred: a file with no matching XML case
shows zero run cases.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

MACRO = re.compile(r'\bTEST(?:_F|_P)?\(\s*([A-Za-z_]\w*)\s*,\s*([A-Za-z_]\w*)\s*\)')


def suite_files(tests_root: pathlib.Path):
    """Map (suite, test name) -> defining file, plus per-file static counts.

    Attribution uses the pair, not the suite alone: a suite name can appear in two files (for example Client).
    """
    pairs, static = {}, {}
    for path in sorted(tests_root.rglob('*.cpp')):
        text = path.read_text(encoding='utf-8', errors='replace')
        rel = path.relative_to(tests_root.parent).as_posix()
        count = 0
        for m in MACRO.finditer(text):
            count += 1
            pairs.setdefault((m.group(1), m.group(2)), set()).add(rel)
        static[rel] = count
    return pairs, static


def read_binary(xml_path: pathlib.Path):
    root = ET.parse(xml_path).getroot()
    cases = []
    for suite in root.iter('testsuite'):
        for case in suite.findall('testcase'):
            failed = case.find('failure') is not None or case.find('error') is not None
            skipped = case.find('skipped') is not None
            cases.append((case.get('classname', ''), case.get('name', ''), failed, skipped))
    return {
        'tests': int(root.get('tests', len(cases))),
        'failures': int(root.get('failures', 0)),
        'disabled': int(root.get('disabled', 0)),
        'time': float(root.get('time', 0.0)),
        'cases': cases,
    }


def attribute(classname, case_name, pairs):
    """Find the source file for one gtest case. Parameterized suites carry a prefix, and their case names carry a
    /param suffix, so both are tried with the prefix and suffix removed."""
    name = case_name.split('/')[0]
    for suite in classname.split('/'):
        files = pairs.get((suite, name))
        if files:
            return files
    return None


def main():
    results_dir, repo_root, out_md = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
    pairs, static = suite_files(repo_root / 'tests')

    binaries = sorted(results_dir.glob('*.xml'))
    per_file = {}
    lines = []
    lines.append('| Binary | Cases run | Passed | Failed | Disabled | Exit code | Time (s) |')
    lines.append('|---|---:|---:|---:|---:|---:|---:|')
    total_run = total_pass = total_fail = 0
    unattributed = []
    for xml in binaries:
        data = read_binary(xml)
        name = xml.stem
        rc_file = results_dir / f'{name}.rc'
        rc = rc_file.read_text().strip() if rc_file.exists() else 'not recorded'
        run = len(data['cases'])
        failed = sum(1 for c in data['cases'] if c[2])
        passed = sum(1 for c in data['cases'] if not c[2] and not c[3])
        total_run += run
        total_pass += passed
        total_fail += failed
        lines.append(f"| {name} | {run} | {passed} | {failed} | {data['disabled']} | {rc} | {data['time']:.1f} |")
        for classname, case_name, is_failed, is_skipped in data['cases']:
            files = attribute(classname, case_name, pairs)
            if files is None:
                unattributed.append(f'{name}: {classname}.{case_name}')
                continue
            for f in files:
                row = per_file.setdefault(f, [0, 0, 0])
                row[0] += 1
                row[1] += 0 if is_failed else 1
                row[2] += 1 if is_failed else 0
    lines.append(f'| **Total** | **{total_run}** | **{total_pass}** | **{total_fail}** | | | |')

    static_total = sum(static.values())
    file_lines = ['| Test file | Test macros | Cases run | Passed | Failed |', '|---|---:|---:|---:|---:|']
    for f in sorted(static):
        run, ok, bad = per_file.get(f, [0, 0, 0])
        file_lines.append(f'| `{f}` | {static[f]} | {run} | {ok} | {bad} |')
    files_with_tests = sum(1 for v in static.values() if v)

    out = []
    out.append('# Test results (offline suites)')
    out.append('')
    out.append('Generated by `tools/summarize_test_results.py` from the gtest XML written by this run. Every number')
    out.append('below comes from that XML. Nothing here was run against Telegram. Live tests are NOT RUN.')
    out.append('')
    out.append('## Per binary')
    out.append('')
    out += lines
    out.append('')
    out.append('"Cases run" counts gtest test instances, so a parameterized test counts once per parameter.')
    out.append(f'Source macros: {static_total} `TEST`/`TEST_F`/`TEST_P` in {files_with_tests} files under `tests/`.')
    out.append('')
    out.append('## Per file')
    out.append('')
    out.append('A file with a macro count and no cases run has tests that did not run in this result set.')
    out.append('')
    out += file_lines
    out.append('')
    if unattributed:
        out.append('## Cases not attributed to a file')
        out.append('')
        out += [f'- {u}' for u in unattributed]
        out.append('')
    out.append('## Not run')
    out.append('')
    out.append('- Live Telegram tests (`BUILD_LIVE_TESTS`, `BUILD_LIVE_CHECK`): NOT RUN. No credentials were used.')
    out.append('- Sanitizer builds (ASan, UBSan, TSan): NOT RUN in this result set. See `BUILD_RESULTS.md`.')
    out.append('- ARM64 build and run: NOT RUN.')
    out.append('- Behavioural match with Kurigram: not tested. The fake DC checks what the client sends and decodes.')
    out_md.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'cases={total_run} passed={total_pass} failed={total_fail} files_with_tests={files_with_tests}')


if __name__ == '__main__':
    main()
