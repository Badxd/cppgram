import re, sys, os
base = sys.argv[1]
def done(path):
    t = open(path, errors='ignore').read()
    m = re.search(r'Done (\d+) runs in (\d+) second', t)
    exit_ = re.search(r'EXIT=(\d+)', t)
    crash = re.search(r'(ERROR: libFuzzer|SUMMARY: \w+Sanitizer|deadly signal)', t)
    return (m.group(1) if m else 'n/a', m.group(2) if m else 'n/a', exit_.group(1) if exit_ else 'no EXIT marker', 'YES' if crash else 'none')
rows = []
f = os.path.join(base, 'fuzz')
for name, fn in [
    ('fuzz_plain_unwrap (instrumented campaign)', 'fuzz_plain_unwrap.log'),
    ('fuzz_decrypt_packet (instrumented campaign)', 'fuzz_decrypt_packet.log'),
    ('fuzz_transport (instrumented campaign)', 'fuzz_transport.log'),
    ('fuzz_plain_unwrap (repo target smoke)', 'repo-smoke2-fuzz_plain_unwrap.log'),
    ('fuzz_decrypt_packet (repo target smoke)', 'repo-smoke2-fuzz_decrypt_packet.log'),
    ('fuzz_transport_framing (repo target smoke)', 'repo-smoke2-fuzz_transport_framing.log'),
]:
    d = done(os.path.join(f, fn))
    if d[2] == 'no EXIT marker':
        s = open(os.path.join(f, 'summary.txt')).read()
        m = re.search(r'^' + fn[:-4] + r' EXIT=(\d+)', s, re.M)
        d = (d[0], d[1], (m.group(1) + ' (from fuzz/summary.txt)') if m else 'no EXIT marker', d[3])
    rows.append((name,) + d)
rows.append(('fuzz_tl_reader (repo target smoke)',) + done(os.path.join(base, 'bot-and-tools', 'fuzz-tl-reader-smoke.log')))
print('# Fuzz results (generated by logs/gen_summaries.py from the logs in this folder; no values typed by hand)')
print('# target | executions | seconds | exit | crash or sanitizer report')
for r in rows: print(' | '.join(str(x) for x in r))
print('# Not run: fuzz_session_string / fuzz_html_parser / fuzz_session_crypto (not in scope of this round); long corpora runs (run_fuzz_long.sh) NOT RUN.')
print('# Not run: malformed-padding-grammar sub-case of the fuzz plan: NOT RUN (documented gap).')
